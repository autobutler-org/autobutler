-- The per-account vault (#3458), the PostgreSQL half of 037_per_account_vault.
-- Column order, nullability and types follow internal/db/AGENTS.md so sqlc
-- generates the same Go types as the SQLite tables.

CREATE TABLE vault_keys (
    user_id             BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    wrapped_by_password BYTEA NOT NULL,
    salt_pw             BYTEA NOT NULL,
    wrapped_by_phrase   BYTEA,
    salt_rp             BYTEA,
    kdf_params          TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((wrapped_by_phrase IS NULL) = (salt_rp IS NULL))
);

CREATE TABLE vault_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    ciphertext     BYTEA NOT NULL,
    nonce          BYTEA NOT NULL,
    format_version BIGINT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_vault_items_user ON vault_items (user_id);

-- Recreates the household vault exactly as 032_baseline defined it, empty but
-- for the vault_location seed row.

CREATE TABLE vault_config (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    salt BYTEA NOT NULL,
    argon2_memory BIGINT NOT NULL DEFAULT 65536,
    argon2_iterations BIGINT NOT NULL DEFAULT 3,
    argon2_parallelism BIGINT NOT NULL DEFAULT 4,
    verification_blob BYTEA NOT NULL,
    verification_nonce BYTEA NOT NULL,
    auto_lock_seconds BIGINT NOT NULL DEFAULT 900,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vault_folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    parent_id BIGINT REFERENCES vault_folders (id) ON DELETE CASCADE,
    sort_order BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vault_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    url_host TEXT NOT NULL DEFAULT '',
    folder_id BIGINT REFERENCES vault_folders (id) ON DELETE SET NULL,
    ciphertext BYTEA NOT NULL,
    nonce BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_vault_entries_folder ON vault_entries (folder_id);

CREATE INDEX idx_vault_entries_url_host ON vault_entries (url_host);

CREATE TABLE vault_location (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    device_serial TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


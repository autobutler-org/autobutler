// Command genpgadapter writes internal/db/pgdb/querier_adapter.go, the type that makes the PostgreSQL queries
// satisfy db.Querier. `make generate/backend/sqlc` runs it after sqlc.
//
// sqlc generates one package per engine, so db.CreateUserParams and pgdb.CreateUserParams are distinct Go types
// even when they are field-for-field identical. The adapter converts between them with plain struct conversions,
// which compile only while the two packages agree on every field name, type and order. A query or a column
// whose PostgreSQL form drifts from its SQLite form is therefore a build failure, not a runtime surprise.
//
// It reads the syntax of internal/db only (go/parser, no type checker): the Querier interface for the methods,
// and the struct declarations to find the rows that embed a model (sqlc.embed), which need a field-by-field
// literal because their field types are themselves package-local.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	srcDir  = "internal/db"
	outFile = "internal/db/pgdb/querier_adapter.go"
	usage   = `Usage: go run ./internal/db/genpgadapter

Writes ` + outFile + ` from the Querier interface sqlc generated in
` + srcDir + `. Run it from the repository root, after sqlc; ` + "`make generate/backend/sqlc`" + ` does both.
`
	header = `// Code generated by internal/db/genpgadapter. DO NOT EDIT.

// Package pgdb is the PostgreSQL half of Quark's query layer: the methods sqlc generates from sql/queries/ and
// sql/queries/postgres/ against the schema in internal/db/migrations_postgres/, and Adapter, which presents them
// as a db.Querier. Nothing opens a PostgreSQL connection with it yet (#2957).
package pgdb

`
	adapter = `// Adapter makes Queries satisfy db.Querier by converting between the two packages' identical structs.
type Adapter struct{ q *Queries }

// NewAdapter returns a db.Querier backed by PostgreSQL over conn: a pool, a connection or a transaction.
func NewAdapter(conn DBTX) *Adapter { return &Adapter{q: New(conn)} }

var _ db.Querier = (*Adapter)(nil)

`
)

func main() {
	if len(os.Args) > 1 {
		fmt.Print(usage)
		if os.Args[1] != "-h" && os.Args[1] != "--help" {
			os.Exit(2)
		}
		return
	}
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "genpgadapter:", err)
		os.Exit(1)
	}
}

func run() error {
	fileSet := token.NewFileSet()
	entries, err := os.ReadDir(srcDir)
	if err != nil {
		return fmt.Errorf("cannot read %s (%w); run this from the repository root", srcDir, err)
	}

	structs := map[string]*ast.StructType{}
	var querier *ast.InterfaceType
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fileSet, filepath.Join(srcDir, name), nil, 0)
		if err != nil {
			return fmt.Errorf("cannot parse %s: %w", name, err)
		}
		ast.Inspect(file, func(n ast.Node) bool {
			spec, ok := n.(*ast.TypeSpec)
			if !ok {
				return true
			}
			switch t := spec.Type.(type) {
			case *ast.StructType:
				structs[spec.Name.Name] = t
			case *ast.InterfaceType:
				if spec.Name.Name == "Querier" {
					querier = t
				}
			}
			return true
		})
	}
	if querier == nil {
		return fmt.Errorf("%s has no Querier interface; run `make generate/backend/sqlc`, which generates it first", srcDir)
	}

	g := generator{fileSet: fileSet, structs: structs}
	methods := querier.Methods.List
	sort.Slice(methods, func(i, j int) bool { return methods[i].Names[0].Name < methods[j].Names[0].Name })
	var body bytes.Buffer
	for _, m := range methods {
		g.method(&body, m.Names[0].Name, m.Type.(*ast.FuncType))
	}

	var out bytes.Buffer
	out.WriteString(header)
	out.WriteString("import (\n\t\"context\"\n")
	// The method signatures name these two packages only when some query takes or returns their types.
	for _, pkg := range []string{"database/sql", "time"} {
		if bytes.Contains(body.Bytes(), []byte(" "+filepath.Base(pkg)+".")) {
			fmt.Fprintf(&out, "\t%q\n", pkg)
		}
	}
	out.WriteString("\n\t\"github.com/autobutler-org/quark/internal/db\"\n)\n\n")
	out.WriteString(adapter)
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return fmt.Errorf("the generated code does not parse, which is a bug in genpgadapter: %w", err)
	}
	if err := os.WriteFile(outFile, src, 0o644); err != nil {
		return fmt.Errorf("%w; run `make generate/backend/sqlc`, which creates %s first", err, filepath.Dir(outFile))
	}
	fmt.Printf("wrote %s: %d methods\n", outFile, len(methods))
	return nil
}

type generator struct {
	fileSet *token.FileSet
	structs map[string]*ast.StructType
}

// local reports the name of a type declared in package db: a bare exported identifier.
func local(t ast.Expr) (string, bool) {
	id, ok := t.(*ast.Ident)
	if !ok {
		return "", false
	}
	return id.Name, ast.IsExported(id.Name)
}

func (g *generator) src(t ast.Expr) string {
	var b bytes.Buffer
	_ = printer.Fprint(&b, g.fileSet, t)
	return b.String()
}

// qualified is how the adapter spells a db type: package-local names gain the db. prefix.
func (g *generator) qualified(t ast.Expr) string {
	if name, ok := local(t); ok {
		return "db." + name
	}
	if arr, ok := t.(*ast.ArrayType); ok && arr.Len == nil {
		return "[]" + g.qualified(arr.Elt)
	}
	return g.src(t)
}

// nested reports whether a struct has a field whose type is package-local, which rules out a plain conversion.
func (g *generator) nested(name string) bool {
	for _, f := range g.structs[name].Fields.List {
		if _, ok := local(f.Type); ok {
			return true
		}
	}
	return false
}

// convert spells expr, a value of the named struct in one package, as the same struct in the other.
// toDB picks the direction: results go to db, params come from it.
func (g *generator) convert(name, expr string, toDB bool) string {
	target := name
	if toDB {
		target = "db." + name
	}
	if g.structs[name] == nil || !g.nested(name) {
		return fmt.Sprintf("%s(%s)", target, expr)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s{", target)
	for _, f := range g.structs[name].Fields.List {
		for _, fn := range f.Names {
			value := expr + "." + fn.Name
			if inner, ok := local(f.Type); ok {
				value = g.convert(inner, value, toDB)
			}
			fmt.Fprintf(&b, "%s: %s, ", fn.Name, value)
		}
	}
	b.WriteString("}")
	return b.String()
}

func (g *generator) method(w *bytes.Buffer, name string, fn *ast.FuncType) {
	var params, args []string
	for _, p := range fn.Params.List {
		for _, pn := range p.Names {
			params = append(params, pn.Name+" "+g.qualified(p.Type))
			if typeName, ok := local(p.Type); ok {
				args = append(args, g.convert(typeName, pn.Name, false))
			} else {
				args = append(args, pn.Name)
			}
		}
	}
	call := fmt.Sprintf("a.q.%s(%s)", name, strings.Join(args, ", "))
	results := fn.Results.List
	if len(results) == 1 { // error only
		fmt.Fprintf(w, "func (a *Adapter) %s(%s) error {\n\treturn %s\n}\n\n", name, strings.Join(params, ", "), call)
		return
	}
	rt := results[0].Type
	fmt.Fprintf(w, "func (a *Adapter) %s(%s) (%s, error) {\n", name, strings.Join(params, ", "), g.qualified(rt))
	switch elem, isLocal := local(rt); {
	case isLocal:
		fmt.Fprintf(w, "\trow, err := %s\n\treturn %s, err\n", call, g.convert(elem, "row", true))
	default:
		arr, isSlice := rt.(*ast.ArrayType)
		var item string
		if isSlice {
			item, isLocal = local(arr.Elt)
		}
		if !isSlice || !isLocal {
			fmt.Fprintf(w, "\treturn %s\n", call)
			break
		}
		// A nil slice stays nil, as sqlc returns it.
		fmt.Fprintf(w, "\trows, err := %s\n\tif err != nil || rows == nil {\n\t\treturn nil, err\n\t}\n", call)
		fmt.Fprintf(w, "\titems := make([]db.%s, len(rows))\n\tfor i, row := range rows {\n\t\titems[i] = %s\n\t}\n\treturn items, nil\n", item, g.convert(item, "row", true))
	}
	w.WriteString("}\n\n")
}
